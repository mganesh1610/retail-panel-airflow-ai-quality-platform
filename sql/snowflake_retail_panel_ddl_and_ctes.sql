-- Snowflake DDL, Staging Validation & Gold Mart CTEs for Retail Consumer Shopping Panel
CREATE SCHEMA IF NOT EXISTS RETAIL_BRONZE;
CREATE SCHEMA IF NOT EXISTS RETAIL_SILVER;
CREATE SCHEMA IF NOT EXISTS RETAIL_QUARANTINE;
CREATE SCHEMA IF NOT EXISTS RETAIL_GOLD;

CREATE TABLE IF NOT EXISTS RETAIL_BRONZE.INVOICE_LINES (
    SOURCE_ROW_ID INTEGER NOT NULL,
    INVOICE_NO VARCHAR(32) NOT NULL,
    STOCK_CODE VARCHAR(32) NOT NULL,
    DESCRIPTION VARCHAR(512),
    QUANTITY INTEGER NOT NULL,
    INVOICE_DATE TIMESTAMP_NTZ NOT NULL,
    UNIT_PRICE_MILLS BIGINT NOT NULL,
    CUSTOMER_ID VARCHAR(32),
    COUNTRY VARCHAR(128) NOT NULL
);

-- CTE Pipeline: Quarantine negative prices, normalize guest checkouts, and compute RFM features
CREATE OR REPLACE VIEW RETAIL_GOLD.VW_COUNTRY_MONTHLY_MART AS
WITH silver_promoted AS (
    SELECT
        SOURCE_ROW_ID,
        INVOICE_NO,
        STOCK_CODE,
        QUANTITY,
        TO_CHAR(INVOICE_DATE, 'YYYY-MM') AS YEAR_MONTH,
        UNIT_PRICE_MILLS,
        (QUANTITY * UNIT_PRICE_MILLS) AS LINE_AMOUNT_MILLS,
        COALESCE(NULLIF(TRIM(CUSTOMER_ID), ''), 'UNKNOWN_GUEST') AS GOVERNED_CUSTOMER_ID,
        CASE WHEN UPPER(INVOICE_NO) LIKE 'C%' THEN 1 ELSE 0 END AS IS_CANCELLATION,
        COUNTRY
    FROM RETAIL_BRONZE.INVOICE_LINES
    WHERE UNIT_PRICE_MILLS >= 0
),
monthly_agg AS (
    SELECT
        YEAR_MONTH,
        COUNTRY,
        COUNT(*) AS LINE_COUNT,
        SUM(CASE WHEN GOVERNED_CUSTOMER_ID = 'UNKNOWN_GUEST' THEN 1 ELSE 0 END) AS GUEST_LINES,
        SUM(CASE WHEN LINE_AMOUNT_MILLS >= 0 THEN LINE_AMOUNT_MILLS ELSE 0 END) AS GROSS_MILLS,
        SUM(CASE WHEN LINE_AMOUNT_MILLS < 0 THEN ABS(LINE_AMOUNT_MILLS) ELSE 0 END) AS CREDIT_MILLS,
        SUM(LINE_AMOUNT_MILLS) AS NET_MILLS
    FROM silver_promoted
    GROUP BY YEAR_MONTH, COUNTRY
)
SELECT * FROM monthly_agg;
